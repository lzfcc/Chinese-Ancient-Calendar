// 模拟获取朔策需要多长时间的观测
function lunar() {
  const result = [];
  for (let j = 13; j < 200; j++) {
    const l = [];
    for (let i = 0; i < 10; i++) {
      l[i] = (a[(i + 1) * j] - a[i * j]) / j;
    }
    let tmp = {};
    tmp.l = l;
    tmp.interval = j;
    tmp.mean = (Math.max(...l) + Math.min(...l)) / 2;
    result.push(tmp);
  }
  return result;
}
